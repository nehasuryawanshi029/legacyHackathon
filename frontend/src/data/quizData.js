export function getQuizQuestions({ subject, topic, difficulty, count }) {
  let pool = QUIZ_QUESTIONS.filter(
    (q) => q.subject === subject && q.topic === topic && q.difficulty === difficulty,
  )

  if (pool.length < count) {
    pool = QUIZ_QUESTIONS.filter((q) => q.subject === subject && q.topic === topic)
  }
  if (pool.length < count) {
    pool = QUIZ_QUESTIONS.filter((q) => q.subject === subject)
  }

  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(count, shuffled.length))
}

export function computeTopicPerformance(questions, answers) {
  const stats = {}

  questions.forEach((q, i) => {
    const key = q.subtopic || q.topic
    if (!stats[key]) stats[key] = { correct: 0, total: 0 }
    stats[key].total += 1
    if (answers[i] === q.correctIndex) stats[key].correct += 1
  })

  return Object.entries(stats).map(([name, { correct, total }]) => ({
    name,
    percent: Math.round((correct / total) * 100),
    isWeak: correct / total < 0.6,
  }))
}
